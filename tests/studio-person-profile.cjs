const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const Planner = require('../assets/js/studio-planner.js');
const planning = Planner.create(); Planner.setCount(planning, 2);
assert.equal(planning.people[0].gender, '');
const source = fs.readFileSync('assets/js/studio.js', 'utf8');
const start = source.indexOf('    profile: function ('), end = source.indexOf('    face: function (', start);
let saves = 0;
const context = { planning, Planner, generationPending: false, updateSummary() {}, selectionChanged() { saves++; } };
vm.createContext(context);
vm.runInContext('var api = {' + source.slice(start, end) + '};', context);
context.api.profile('Linh', '170', '60', 'female');
assert.equal(planning.people[0].gender, 'female');
assert.equal(planning.people[1].gender, '', 'shared outfits never copy gender');
planning.activePerson = 2;
context.api.profile('An', '', '', 'male');
assert.equal(planning.people[0].gender, 'female');
assert.equal(planning.people[1].gender, 'male');
for (const invalid of ['unknown', 'FEMALE', {}, 1]) {
  assert.throws(() => context.api.profile('Changed', '', '', invalid));
  assert.equal(planning.people[1].name, 'An', 'validation must be atomic');
}
context.generationPending = true;
context.api.profile('Changed', '', '', 'other');
assert.equal(planning.people[1].gender, 'male', 'pending generation locks profile');
context.generationPending = false;
context.api.profile('An', '', '', 'other');
const restored = Planner.restore({ planning: Planner.clone(planning) });
assert.equal(restored.people[0].gender, 'female');
assert.equal(restored.people[1].gender, 'other');
delete restored.people[0].gender;
assert.equal(Planner.restore({ planning: restored }).people[0].gender, '', 'old drafts gain an optional empty gender');
assert.equal(Planner.restore({ garment: 'ao-tac' }).people[0].gender, '', 'legacy single looks remain editable');
context.api.profile('An', '', '', '');
assert.equal(planning.people[1].gender, '', 'clear selection must persist');
assert.equal(saves, 4);
const ui = fs.readFileSync('assets/js/studio-planner-ui.js', 'utf8');
const commitStart = ui.indexOf('  function commitProfile()'), commitEnd = ui.indexOf('  function render()', commitStart);
const fields = { personName: { value: 'An' }, personHeight: { value: '' }, personWeight: { value: '' }, personGender: { value: 'female' } };
const commit = { id: key => fields[key], api: { get: () => planning, profile: context.api.profile }, action(fn) { fn(); return true; } };
vm.createContext(commit); vm.runInContext(ui.slice(commitStart, commitEnd), commit);
commit.commitProfile();
assert.equal(planning.people[1].gender, 'female', 'gender-only edits commit before switching/review');
commit.commitProfile(); assert.equal(saves, 5, 'unchanged fields must not repeatedly save');
const markup = fs.readFileSync('includes/studio/planner-person.php', 'utf8');
assert.match(markup, /select id="personGender" aria-describedby="personGenderHint"/);
assert.match(markup, /option value="">Không chọn/);
assert.match(markup, /personFaceConsent/);
assert.match(markup, /id="personFace"[^>]+disabled/);
const css = fs.readFileSync('assets/css/studio-workspace.css', 'utf8');
assert.match(css, /\.planner-person-tabs \+ \.guide-card-note \{ margin-top: 12px;/);
assert.match(css, /\.planner-person-fields \{ display: grid; gap: 18px;/);
console.log('Studio person profile: optional gender, isolated people, atomic validation, generation lock, legacy restore, clearing, UI commit, spacing and face consent passed.');

const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('assets/js/studio.js', 'utf8');
function extract(start, end) { return source.slice(source.indexOf(start), source.indexOf(end, source.indexOf(start))); }
const controls = { saveLookButton: { disabled: false }, compareLooksButton: { disabled: false }, resultDownload: { hidden: false } };
const context = { ...controls, currentLookbookItems: [{ url: 'old-result' }], currentResultSelection: null, draftEdited: false, syncSubmitButton() {}, persistStudio() {}, setStatus() {} };
vm.runInNewContext(extract('  function selectionChanged()', '  async function generateLook(') + '\nselectionChanged();', context);
assert.equal(controls.saveLookButton.disabled, false, 'editing does not prevent saving the previous result');
assert.equal(controls.resultDownload.hidden, false, 'editing does not prevent downloading the previous result');
const show = { result: {}, document: { body: { style: {} } }, currentLookbookItems: [{ url: 'old-result' }], syncSubmitButton() {} };
vm.runInNewContext(extract('  function showResult()', '  function hideResult()') + '\nshowResult();', show);
assert.equal(show.currentLookbookItems[0].url, 'old-result', 'starting again never destroys the old result');
assert.match(source, /unresolvedJob.*readActiveJob\(\)/s);
assert.match(source, /return resumeGeneration\(unresolvedJob\)/);
assert.match(source, /saveId: resultSaveId/);
assert.match(source, /canvas.width = 1080;\s*canvas.height = 1920;/);
assert.match(source, /fetch\(currentLookbookItems\[0\].url\)/, 'original download is independent of story export');
const session = fs.readFileSync('assets/js/studio-session.js', 'utf8');
assert.match(session, /person.faceSupplied = false/);
assert.match(session, /record.userId && record.userId !== config.auth.userId/);
const nav = fs.readFileSync('includes/studio/workspace-navigation.php', 'utf8');
assert.match(nav, /data-workspace-collections[^>]*aria-label="Bộ sưu tập của tôi"[^>]*disabled>/);
const api = fs.readFileSync('look-api.php', 'utf8');
assert.match(api, /verifyCsrf/);
assert.match(api, /'user_id' => 'eq\.' \./);
assert.match(api, /rpc\('save_studio_look'/);
assert.match(api, /uploadData/);
assert.match(api, /generation_job_id/);
const local = fs.readFileSync('local-generate.php', 'utf8');
assert.match(local, /session_write_close\(\)/);
assert.match(local, /reserve_local_generation/);
assert.match(local, /owner_session_hash/);
assert.match(local, /'status' => 'eq.queued'/);
console.log('Studio lifecycle: old result safety, unresolved job reuse, private library, durable draft and separate exports passed offline.');

const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('assets/js/studio-planner-ui.js', 'utf8');
const start=source.indexOf("    id('groupCount').value"), end=source.indexOf("    document.querySelectorAll('[data-period]')",start);
const nodes=Object.fromEntries(['groupCount','chooseGroup','groupCountFields','plannerPeopleSummary'].map(id=>[id,{attributes:{},setAttribute(k,v){this.attributes[k]=v;}}]));

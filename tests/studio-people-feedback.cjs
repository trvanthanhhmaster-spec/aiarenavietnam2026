const context={plan:{count:null},id:key=>nodes[key],document:{querySelectorAll:()=>buttons}};
vm.createContext(context);
for(const count of [null,1,2,5,12,2,1]) {
  context.plan.count=count; vm.runInContext(source.slice(start,end),context);
  assert.equal(nodes.chooseGroup.attributes['aria-pressed'],String(count>2));
  assert.equal(nodes.groupCountFields.hidden,!(count>2));
  assert.equal(nodes.plannerPeopleSummary.hidden,!count);
  assert.equal(nodes.plannerPeopleSummary.textContent,count?'Đã chọn '+count+' người. Tiếp tục để chọn thời gian.':'');
  for(const b of buttons) assert.equal(b.attributes['aria-pressed'],String(Number(b.dataset.personCount)===count));
}

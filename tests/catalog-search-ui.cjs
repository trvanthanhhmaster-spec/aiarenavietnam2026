const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const code = fs.readFileSync(require('node:path').join(__dirname, '../assets/js/catalog-search.js'), 'utf8');
const handlers = {};
const imageHandlers = {};
const button = { innerHTML: '<svg></svg>Tìm nguồn', textContent: '', disabled: false, dataset: { busyLabel: 'Đang tìm nguồn…' } };
const form = { valid: true, attrs: {}, addEventListener: (type, fn) => handlers[type] = fn, checkValidity() { return this.valid; }, querySelector: () => button, setAttribute(key, value) { this.attrs[key] = value; }, removeAttribute(key) { delete this.attrs[key]; } };
const notice = { hidden: true };
const image = { complete: true, naturalWidth: 0, hidden: false, addEventListener: (type, fn) => imageHandlers[type] = fn, parentElement: { querySelector: () => notice } };
let restore;
vm.runInNewContext(code, { document: { querySelectorAll: selector => selector.includes('form') ? [form] : [image] }, window: { addEventListener: (type, fn) => restore = fn } });
assert.equal(image.hidden, true);
assert.equal(notice.hidden, false);
const submit = () => { const event = { defaultPrevented: false, preventDefault() { this.defaultPrevented = true; } }; handlers.submit(event); return event; };
form.valid = false; submit(); assert.equal(button.disabled, false);
form.valid = true; submit(); assert.equal(button.disabled, true); assert.equal(form.attrs['aria-busy'], 'true'); assert.equal(button.textContent, 'Đang tìm nguồn…');
assert.equal(submit().defaultPrevented, true);
restore(); assert.equal(button.disabled, false); assert.equal(button.innerHTML, '<svg></svg>Tìm nguồn'); assert.equal(form.attrs['aria-busy'], undefined);
button.disabled = true; submit(); restore(); assert.equal(button.disabled, true, 'Original unavailable AI action remains disabled');
assert(!code.includes('fetch('), 'No automatic provider calls');
console.log('Catalog search UI contracts passed.');

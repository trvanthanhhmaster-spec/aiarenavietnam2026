const assert = require('node:assert/strict');
const model = require('../assets/js/studio-collections-model.js');
let counter = 0;
const store = model.create(() => 'id-' + ++counter, selection => selection.event);
store.ingest({ draft: { event: 'Đi bay' }, selection: { event: 'Đi bay' }, jobId: 'job-a' });
const first = store.active();
store.start();
const blank = store.capture({ draft: { event: '' }, jobId: null });
assert.equal(blank.collections.length, 1, 'blank studio preserves old collection');
assert.equal(store.get(first).record.jobId, 'job-a');
store.capture({ draft: { event: 'Dự lễ' }, jobId: 'job-b' });
assert.equal(store.list().length, 2);
store.select(first);
assert.equal(store.get(store.active()).record.draft.event, 'Đi bay');
store.importHistory([{ ids: ['job-a'], record: { draft: { event: 'Duplicate' }, jobId: 'job-a' } }]);
assert.equal(store.list().length, 2, 'existing chains are not duplicated');
const restored = model.create(() => 'restored', s => s.event);
restored.ingest(store.capture(store.get(first).record));
assert.equal(restored.active(), first);
assert.equal(restored.list().length, 2);
console.log('Collections: legacy import, blank reset, isolation, restore and deduplication passed.');
